/* Стажёр: «лёгкий вход». Мелкие задания по одному шагу, как в популярных курсах (Stepik, CS50P, Codecademy):
   сначала тренируем одну мысль, потом идём к большим задачам.
   Здесь же три новых урока (вывод и ввод, числа, логика) и «разминки» внутри старых уроков. */

/* маленькое задание: ET(id, текст, заготовка, решение, тест, примеры, шаги, подсказка) + разбор в plans */
const ET = (id, text, starter, solution, test, ex, steps, hint, stdin) => {
  PL(id, ex, steps, {lvl: 1});
  return T({id, text, starter, test, solution, hint, ...(stdin ? {stdin} : {})});
};

/* то же, но для функции (таблица случаев) */
const EF = o => { const t = F({...o, d: 1}); PL(o.id, t.ex, o.plan, {lvl: 1}); return t; };

/* тест «на других данных»: убираем строки с исходными значениями и подставляем свои.
   inputs — имена переменных с данными, outs — что проверяем, cases — Python-список [({входы}, ожидаемое), ...] */
const RT = (inputs, outs, cases) => String.raw`
import re
_lines = __src__.splitlines()
for _n in ${JSON.stringify(inputs)}:
    for _i, _l in enumerate(_lines):
        if re.match(_n + r"\s*=(?!=)", _l):
            del _lines[_i]
            break
_body = "\n".join(_lines)
def _eq(a, b):
    return abs(a - b) < 1e-9 if isinstance(b, float) and isinstance(a, (int, float)) else a == b
for _in, _want in ${cases}:
    _g = dict(_in); exec(_body, _g)
    _got = ${outs.length === 1 ? `_g["${outs[0]}"]` : `(${outs.map(o => `_g["${o}"]`).join(', ')})`}
    assert _eq(_got, _want), f"при {_in} получилось {_got!r}, а нужно {_want!r}"`;

/* вставляет «разминку» в готовый урок: перед первым заданием */
